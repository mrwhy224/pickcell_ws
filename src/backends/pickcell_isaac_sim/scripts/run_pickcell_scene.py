"""Import PickCell, render an overhead RGB-D camera, and publish ROS 2 data."""

import argparse
import json
from pathlib import Path
import random
import shutil


def parse_arguments():
    """Parse arguments before starting Isaac Sim."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--urdf", required=True)
    parser.add_argument("--usd-dir", required=True)
    parser.add_argument("--pickcell-description", required=True)
    parser.add_argument("--kuka-description", required=True)
    parser.add_argument("--headless", action="store_true")
    parser.add_argument("--test-steps", type=int, default=0)
    parser.add_argument("--dataset-samples", type=int, default=0)
    parser.add_argument("--dataset-output", default="datasets/bags_synthetic")
    parser.add_argument("--dataset-seed", type=int, default=42)
    parser.add_argument("--min-bags", type=int, default=1)
    parser.add_argument("--max-bags", type=int, default=9)
    return parser.parse_known_args()


args, _unknown = parse_arguments()

from isaacsim import SimulationApp


simulation_app = SimulationApp({
    "renderer": "RayTracedLighting",
    "headless": args.headless,
})

